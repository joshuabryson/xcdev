#!/bin/sh
# Regenerates Sources/XcdevKit/Guides/GuideText*.swift from docs/agents/guides/*.md, so the binary carries the
# guides with no resource bundle. Run it after editing a guide; GuidesTests fails until you do.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
dir="$root/Sources/XcdevKit/Guides"
mkdir -p "$dir"
rm -f "$dir"/GuideText*.swift      # every file of that name is generated here, also one for a guide that is gone

# The constant that holds a topic's text: "deeplinks" is guideDeeplinks.
constant() {
    printf '%s' "$1" | awk '{ gsub(/[^A-Za-z0-9]/, ""); print "guide" toupper(substr($0, 1, 1)) substr($0, 2) }'
}

# Each guide is a constant in a file of its own, so that no file and no type's body grows with the guides.
for file in "$root"/docs/agents/guides/*.md; do
    topic=$(basename "$file" .md)
    {
        echo "// Generated by scripts/embed-guides.sh from docs/agents/guides/$topic.md. Edit the Markdown, then re-run the script."
        printf '\n/// docs/agents/guides/%s.md\nlet %s = #"""\n' "$topic" "$(constant "$topic")"
        cat "$file"
        printf '"""#\n'
    } > "$dir/GuideText+$topic.swift"
done

{
    echo "// Generated by scripts/embed-guides.sh from docs/agents/guides/*.md. Edit the Markdown, then re-run the script."
    echo
    echo "enum GuideText {"
    echo "    static let topics: [String: String] = ["
    for file in "$root"/docs/agents/guides/*.md; do
        topic=$(basename "$file" .md)
        printf '        "%s": %s,\n' "$topic" "$(constant "$topic")"
    done
    echo "    ]"
    echo "}"
} > "$dir/GuideText.swift"
echo "wrote $dir/GuideText.swift and one file per guide"

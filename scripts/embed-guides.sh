#!/bin/sh
# Regenerates Sources/XcdevKit/Guides/GuideText.swift from docs/agents/guides/*.md, so the binary carries the
# guides with no resource bundle. Run it after editing a guide; GuidesTests fails until you do.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/Sources/XcdevKit/Guides/GuideText.swift"
mkdir -p "$(dirname "$out")"

# The constant that holds a topic's text: "deeplinks" is guideDeeplinks.
constant() {
    printf '%s' "$1" | awk '{ gsub(/[^A-Za-z0-9]/, ""); print "guide" toupper(substr($0, 1, 1)) substr($0, 2) }'
}

{
    echo "// Generated by scripts/embed-guides.sh from docs/agents/guides/*.md. Edit the Markdown, then re-run the script."
    # Each guide is a constant of its own, so that no type's body grows with the guides.
    for file in "$root"/docs/agents/guides/*.md; do
        topic=$(basename "$file" .md)
        printf '\n/// docs/agents/guides/%s.md\nprivate let %s = #"""\n' "$topic" "$(constant "$topic")"
        cat "$file"
        printf '"""#\n'
    done
    echo
    echo "enum GuideText {"
    echo "    static let topics: [String: String] = ["
    for file in "$root"/docs/agents/guides/*.md; do
        topic=$(basename "$file" .md)
        printf '        "%s": %s,\n' "$topic" "$(constant "$topic")"
    done
    echo "    ]"
    echo "}"
} > "$out"
echo "wrote $out"

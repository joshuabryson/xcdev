#!/bin/sh
# Regenerates Sources/XcdevKit/UIRunner/EmbeddedRunner.swift from the runner project and the RunnerCore files, so the
# xcd binary carries the UI runner's source with no resource bundle. The files go into one container
# (`path NUL byteCount NUL bytes`, repeated), gzip-compressed and base64-encoded. Run it after editing anything under
# Sources/XcdevKit/UIRunner/Project or Sources/XcdevKit/UIRunner/Core; RunnerSourceTests fails until you do.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
project="$root/Sources/XcdevKit/UIRunner/Project"
core="$root/Sources/XcdevKit/UIRunner/Core"
out="$root/Sources/XcdevKit/UIRunner/EmbeddedRunner.swift"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Writes the files to embed, as sorted paths relative to their folder: the project's to project.txt, Core's to core.txt.
# Each find is a command of its own, so `set -e` stops the script when one fails, and an empty list is an error.
list() {
    (cd "$project" && find . -type f ! -name .DS_Store ! -path '*/xcuserdata/*' ! -path '*/project.xcworkspace/*') > "$work/project.found"
    sed 's|^\./||' "$work/project.found" | LC_ALL=C sort > "$work/project.txt"
    (cd "$core" && find . -type f -name '*.swift') > "$work/core.found"
    sed 's|^\./||' "$work/core.found" | LC_ALL=C sort > "$work/core.txt"
    if [ ! -s "$work/project.txt" ] || [ ! -s "$work/core.txt" ]; then
        echo "embed-runner: found no files in $project or in $core" >&2
        exit 1
    fi
}
add() {
    # $1: path inside the written project, $2: source file
    printf '%s\0%s\0' "$1" "$(wc -c < "$2" | tr -d ' ')"
    cat "$2"
}
list
: > "$work/container"
while IFS= read -r file; do
    add "$file" "$project/$file" >> "$work/container" || exit 1
done < "$work/project.txt"
while IFS= read -r file; do
    add "XcdRunner/Core/$file" "$core/$file" >> "$work/container" || exit 1
done < "$work/core.txt"

gzip -n -9 < "$work/container" > "$work/container.gz"
base64 < "$work/container.gz" > "$work/container.b64"
fold -w 112 < "$work/container.b64" > "$work/container.folded"
sed 's/^/        /' "$work/container.folded" > "$work/container.indented"

# The archive is a file-scope constant and the enum only names it, so the enum's body stays a few lines long however
# large the runner grows.
{
    echo "// Generated by scripts/embed-runner.sh from Sources/XcdevKit/UIRunner/Project and Core. Edit those, then re-run the script."
    echo "enum EmbeddedRunner {"
    echo "    /// The runner's files: \`path NUL byteCount NUL bytes\`, repeated; gzip-compressed, then base64."
    echo "    static let archive = embeddedRunnerArchive"
    echo "}"
    echo ""
    echo 'private let embeddedRunnerArchive = """'
    cat "$work/container.indented"
    echo '        """'
} > "$work/EmbeddedRunner.swift"
mv "$work/EmbeddedRunner.swift" "$out"
echo "wrote $out"
